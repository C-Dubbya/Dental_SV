-- 1 -> 10_dental_procedure_context.csv
-- Restores aggregate procedure evidence and adds source descriptions/categories/units.
-- Descriptions and CCS categories are source attributes, not approved Dental cohorts.
-- Export all rows; do not restrict to positive amounts or D-prefixed procedure codes.
SELECT
    C.CLAIM_STATUS_CD,
    C.PROCEDURE_CD,
    C.PROCEDURE_DESC,
    C.SERVICE_PROCEDURE_CCS_CATEGORY_CD,
    C.SERVICE_PROCEDURE_CCS_CATEGORY_DESC,
    COUNT(*) AS CLAIM_LINE_COUNT,
    COUNT(DISTINCT C.CLAIM_ICN_NBR) AS CLAIM_COUNT,
    COUNT(DISTINCT C.BENEFICIARY_ID) AS MEMBER_COUNT,
    COUNT_IF(C.LINE_PAID_AMT = 0) AS ZERO_PAID_LINES,
    SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT,
    SUM(C.LINE_ALLOW_AMT) AS ALLOWED_AMOUNT,
    SUM(C.LINE_BILL_AMT) AS BILLED_AMOUNT,
    COUNT_IF(C.PROCEDURE_DIM_SK > 0) AS POSITIVE_PROCEDURE_REFERENCE_KEY_LINES,
    COUNT_IF(C.BILL_QTY IS NULL) AS NULL_BILLED_QTY_LINES,
    COUNT_IF(C.BILL_QTY = 0) AS ZERO_BILLED_QTY_LINES,
    COUNT_IF(C.BILL_QTY < 0) AS NEGATIVE_BILLED_QTY_LINES,
    MIN(C.BILL_QTY) AS MIN_BILLED_QTY,
    MAX(C.BILL_QTY) AS MAX_BILLED_QTY,
    SUM(C.BILL_QTY) AS BILLED_QTY,
    COUNT_IF(C.ALLOW_QTY IS NULL) AS NULL_ALLOWED_QTY_LINES,
    COUNT_IF(C.ALLOW_QTY = 0) AS ZERO_ALLOWED_QTY_LINES,
    COUNT_IF(C.ALLOW_QTY < 0) AS NEGATIVE_ALLOWED_QTY_LINES,
    MIN(C.ALLOW_QTY) AS MIN_ALLOWED_QTY,
    MAX(C.ALLOW_QTY) AS MAX_ALLOWED_QTY,
    SUM(C.ALLOW_QTY) AS ALLOWED_QTY
FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
  AND C.CLAIM_STATUS_CD IN ('P', 'D')
  AND C.CLAIM_VOID_IND = 'N'
  AND C.LAST_CLAIM_IND = 'Y'
GROUP BY C.CLAIM_STATUS_CD, C.PROCEDURE_CD, C.PROCEDURE_DESC,
         C.SERVICE_PROCEDURE_CCS_CATEGORY_CD, C.SERVICE_PROCEDURE_CCS_CATEGORY_DESC
ORDER BY C.CLAIM_STATUS_CD, PAID_AMOUNT DESC NULLS LAST, C.PROCEDURE_CD, C.PROCEDURE_DESC;

-- 2 -> 11_dental_status_dates.csv
-- Distinguish header status from line status and header service date from line date.
-- Preserve all combinations, including placeholders. Do not replace header P/D scope.
-- Capture payment-level, encounter and contract markers rather than inferring them
-- from CLAIM_TYPE_CD = D. Row-touch timestamps do not prove a warehouse refresh date.
SELECT
    C.CLAIM_STATUS_CD,
    C.LINE_STATUS_CD,
    C.LINE_STATUS_DESC,
    C.PAYMENT_LEVEL_CD,
    C.PAYMENT_LEVEL_DESC,
    C.ENCOUNTER_IND,
    C.CONTRACT_TYPE_CD,
    C.CONTRACT_TYPE_DESC,
    COUNT(*) AS CLAIM_LINE_COUNT,
    COUNT(DISTINCT C.CLAIM_ICN_NBR) AS CLAIM_COUNT,
    COUNT_IF(C.LINE_PAID_AMT = 0) AS ZERO_PAID_LINES,
    SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT,
    SUM(C.LINE_ENCOUNTER_PAID_AMT) AS ENCOUNTER_PAID_AMOUNT,
    COUNT_IF(C.LINE_FIRST_SERVICE_DT IS NULL) AS NULL_LINE_FIRST_SERVICE_DATES,
    COUNT_IF(C.LINE_LAST_SERVICE_DT IS NULL) AS NULL_LINE_LAST_SERVICE_DATES,
    COUNT_IF(C.CLAIM_FIRST_SERVICE_DT <> C.LINE_FIRST_SERVICE_DT) AS CLAIM_LINE_FIRST_DATE_DIFFERENCES,
    COUNT_IF(C.CLAIM_FIRST_SERVICE_DT > C.CLAIM_LAST_SERVICE_DT) AS REVERSED_CLAIM_SERVICE_RANGES,
    COUNT_IF(C.LINE_FIRST_SERVICE_DT > C.LINE_LAST_SERVICE_DT) AS REVERSED_LINE_SERVICE_RANGES,
    COUNT_IF(C.CLAIM_PAID_DT < C.CLAIM_FIRST_SERVICE_DT) AS PAID_BEFORE_CLAIM_SERVICE_LINES,
    SUM(IFF(C.CLAIM_PAID_DT < C.CLAIM_FIRST_SERVICE_DT, C.LINE_PAID_AMT, 0)) AS PAID_BEFORE_CLAIM_SERVICE_AMOUNT,
    COUNT_IF(C.CLAIM_PAID_DT < C.LINE_FIRST_SERVICE_DT) AS PAID_BEFORE_LINE_SERVICE_LINES,
    SUM(IFF(C.CLAIM_PAID_DT < C.LINE_FIRST_SERVICE_DT, C.LINE_PAID_AMT, 0)) AS PAID_BEFORE_LINE_SERVICE_AMOUNT,
    MIN(DATEDIFF(DAY, C.LINE_FIRST_SERVICE_DT, C.CLAIM_PAID_DT)) AS MIN_LINE_SERVICE_PAID_LAG_DAYS,
    MAX(DATEDIFF(DAY, C.LINE_FIRST_SERVICE_DT, C.CLAIM_PAID_DT)) AS MAX_LINE_SERVICE_PAID_LAG_DAYS,
    MIN(C.DE_LOAD_TS) AS EARLIEST_SOURCE_ROW_LOAD_TS,
    MAX(C.DE_LOAD_TS) AS LATEST_SOURCE_ROW_LOAD_TS,
    MAX(C.DE_UPDT_TS) AS LATEST_SOURCE_ROW_UPDATE_TS
FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
  AND C.CLAIM_STATUS_CD IN ('P', 'D')
  AND C.CLAIM_VOID_IND = 'N'
  AND C.LAST_CLAIM_IND = 'Y'
GROUP BY C.CLAIM_STATUS_CD, C.LINE_STATUS_CD, C.LINE_STATUS_DESC,
         C.PAYMENT_LEVEL_CD, C.PAYMENT_LEVEL_DESC, C.ENCOUNTER_IND,
         C.CONTRACT_TYPE_CD, C.CONTRACT_TYPE_DESC
ORDER BY C.CLAIM_STATUS_CD, C.LINE_STATUS_CD, C.PAYMENT_LEVEL_CD,
         C.ENCOUNTER_IND, C.CONTRACT_TYPE_CD;

-- 3 -> 12_dental_field_coverage.csv
-- Direct claim-side age/plan slices do not need the service-date PMPM join.
-- Confirm validity before choosing those fields over the inherited profile logic.
-- Candidate-present text screening excludes common placeholders, not a validated
-- source-specific code set. Positive surrogate keys do not prove dimension matches.
WITH dental AS (
    SELECT C.*,
        DATEDIFF(YEAR, C.BENEFICIARY_BIRTH_DT, C.LINE_FIRST_SERVICE_DT)
          - IFF(DATEADD(YEAR,
                DATEDIFF(YEAR, C.BENEFICIARY_BIRTH_DT, C.LINE_FIRST_SERVICE_DT),
                C.BENEFICIARY_BIRTH_DT) > C.LINE_FIRST_SERVICE_DT, 1, 0) AS CALCULATED_AGE_AT_LINE_SERVICE
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P', 'D')
      AND C.CLAIM_VOID_IND = 'N'
      AND C.LAST_CLAIM_IND = 'Y'
), classified AS (
    SELECT *, CASE
        WHEN BENEFICIARY_AGE_YRS IS NULL THEN 'Unknown source age'
        WHEN BENEFICIARY_AGE_YRS < 0 THEN 'Invalid negative source age'
        WHEN BENEFICIARY_AGE_YRS < 21 THEN '0-20 at source age anchor'
        ELSE '21+ at source age anchor'
    END AS SOURCE_AGE_BAND
    FROM dental
)
SELECT
    CLAIM_STATUS_CD,
    HEALTH_PROGRAM_CD,
    HEALTH_PLAN_ID,
    SOURCE_AGE_BAND,
    COUNT(*) AS CLAIM_LINE_COUNT,
    COUNT(DISTINCT CLAIM_ICN_NBR) AS CLAIM_COUNT,
    COUNT(DISTINCT BENEFICIARY_ID) AS MEMBER_COUNT,
    SUM(LINE_PAID_AMT) AS PAID_AMOUNT,
    MIN(BENEFICIARY_AGE_YRS) AS MIN_SOURCE_AGE_YRS,
    MAX(BENEFICIARY_AGE_YRS) AS MAX_SOURCE_AGE_YRS,
    COUNT_IF(BENEFICIARY_BIRTH_DT IS NULL) AS MISSING_SOURCE_DOB_LINES,
    COUNT_IF(BENEFICIARY_BIRTH_DT > LINE_FIRST_SERVICE_DT) AS DOB_AFTER_LINE_SERVICE_LINES,
    COUNT_IF(BENEFICIARY_AGE_YRS <> CALCULATED_AGE_AT_LINE_SERVICE) AS SOURCE_CALCULATED_AGE_DIFFERENCES,
    COUNT_IF(BENEFICIARY_AGE_YRS IS NOT NULL AND CALCULATED_AGE_AT_LINE_SERVICE IS NOT NULL) AS AGE_COMPARABLE_LINES,
    COUNT_IF(RENDER_MMIS_PROVLOC_DIM_SK > 0) AS POSITIVE_RENDER_PROVLOC_KEY_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(RENDER_MMIS_PROVIDER_ID)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_RENDER_PROVIDER_ID_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(RENDER_MMIS_PROVLOC_ID)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_RENDER_LOCATION_ID_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(TOOTH_NBR_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_TOOTH_NUMBER_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(TOOTH_QUADRANT_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_TOOTH_QUADRANT_LINES,
    COUNT_IF(
        COALESCE(UPPER(TRIM(TOOTH_SURFACE_1_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')
        OR COALESCE(UPPER(TRIM(TOOTH_SURFACE_2_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')
        OR COALESCE(UPPER(TRIM(TOOTH_SURFACE_3_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')
        OR COALESCE(UPPER(TRIM(TOOTH_SURFACE_4_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')
        OR COALESCE(UPPER(TRIM(TOOTH_SURFACE_5_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')
    ) AS CANDIDATE_ANY_TOOTH_SURFACE_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(POS_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_PLACE_OF_SERVICE_LINES,
    COUNT_IF(COALESCE(UPPER(TRIM(PROCEDURE_MODIFIER_1_CD)), '') NOT IN ('', 'BLANK', 'N/A', 'NA')) AS CANDIDATE_FIRST_MODIFIER_LINES
FROM classified
GROUP BY CLAIM_STATUS_CD, HEALTH_PROGRAM_CD, HEALTH_PLAN_ID, SOURCE_AGE_BAND
ORDER BY CLAIM_STATUS_CD, HEALTH_PROGRAM_CD, HEALTH_PLAN_ID, SOURCE_AGE_BAND;

