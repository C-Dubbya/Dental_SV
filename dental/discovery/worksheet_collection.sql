-- Dental first-pass collection: run in a Snowflake SQL worksheet.
-- Required: export statements 1-3 as CSV, with the filenames below.
-- Optional: statement 4 adds selected example rows; it is NOT a statistical sample.
-- No CoWork, INFORMATION_SCHEMA, session variables, temp objects or source writes.
-- All-date aggregates deliberately avoid choosing a window before seeing available dates.

-- 1 -> 01_claim_line_columns.csv
-- Full result includes declared types/comments where exposed by DESCRIBE.
DESC TABLE TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT;

-- 2 -> 02_dental_baseline.csv
-- One row per source category + status + type. Includes P zero-dollar lines.
-- Members/ICNs can overlap across groups; do not add distinct counts for a total.
SELECT
    C.CLAIM_CATEGORY_CD,
    C.CLAIM_STATUS_CD,
    C.CLAIM_TYPE_CD,
    C.CLAIM_TYPE_DESC,
    COUNT(*) AS CLAIM_LINE_COUNT,
    COUNT(DISTINCT C.CLAIM_ICN_NBR) AS CLAIM_COUNT,
    COUNT(DISTINCT C.BENEFICIARY_ID) AS MEMBER_COUNT,
    COUNT(DISTINCT C.PROCEDURE_CD) AS DISTINCT_PROCEDURE_CODES,
    COUNT_IF(C.CLAIM_ICN_NBR IS NULL OR C.CLAIM_LINE_NBR IS NULL) AS NULL_LINE_KEYS,
    COUNT_IF(C.BENEFICIARY_ID IS NULL) AS NULL_MEMBER_KEYS,
    COUNT_IF(NULLIF(TRIM(C.PROCEDURE_CD), '') IS NULL) AS MISSING_PROCEDURE_LINES,
    COUNT_IF(C.CLAIM_FIRST_SERVICE_DT IS NULL) AS NULL_SERVICE_DATES,
    COUNT_IF(C.CLAIM_PAID_DT IS NULL) AS NULL_PAID_DATES,
    MIN(C.CLAIM_FIRST_SERVICE_DT) AS FIRST_SERVICE_DT,
    MAX(C.CLAIM_FIRST_SERVICE_DT) AS LATEST_SERVICE_DT,
    MIN(C.CLAIM_PAID_DT) AS FIRST_PAID_DT,
    MAX(C.CLAIM_PAID_DT) AS LATEST_PAID_DT,
    COUNT_IF(C.LINE_PAID_AMT IS NULL) AS NULL_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT = 0) AS ZERO_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT < 0) AS NEGATIVE_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT > 0) AS POSITIVE_PAID_LINES,
    COUNT_IF(C.LINE_ALLOW_AMT <> 0) AS NONZERO_ALLOWED_LINES,
    COUNT_IF(C.LINE_ENCOUNTER_PAID_AMT <> 0) AS NONZERO_ENCOUNTER_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT <> 0 AND C.LINE_ENCOUNTER_PAID_AMT <> 0) AS BOTH_PAID_CHANNELS_LINES,
    SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT,
    SUM(C.LINE_ALLOW_AMT) AS ALLOWED_AMOUNT,
    SUM(C.LINE_BILL_AMT) AS BILLED_AMOUNT,
    SUM(C.LINE_ENCOUNTER_PAID_AMT) AS ENCOUNTER_PAID_AMOUNT,
    SUM(C.LINE_ENCOUNTER_ALLOW_AMT) AS ENCOUNTER_ALLOWED_AMOUNT,
    SUM(C.LINE_CO_PAY_AMT) AS COPAY_AMOUNT
FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
  AND C.CLAIM_STATUS_CD IN ('P', 'D')
  AND C.CLAIM_VOID_IND = 'N'
  AND C.LAST_CLAIM_IND = 'Y'
GROUP BY C.CLAIM_CATEGORY_CD, C.CLAIM_STATUS_CD, C.CLAIM_TYPE_CD, C.CLAIM_TYPE_DESC
ORDER BY C.CLAIM_CATEGORY_CD, C.CLAIM_STATUS_CD, C.CLAIM_TYPE_CD, C.CLAIM_TYPE_DESC;

-- 3 -> 03_dental_procedure_profile.csv
-- Export ALL rows. Raw codes are not assigned clinical service groups here.
-- Null/blank/placeholder values remain visible. ICN/member counts are not additive.
SELECT
    C.PROCEDURE_CD,
    C.CLAIM_STATUS_CD,
    C.CLAIM_TYPE_CD,
    COUNT(*) AS CLAIM_LINE_COUNT,
    COUNT(DISTINCT C.CLAIM_ICN_NBR) AS CLAIM_COUNT,
    COUNT(DISTINCT C.BENEFICIARY_ID) AS MEMBER_COUNT,
    MIN(C.CLAIM_FIRST_SERVICE_DT) AS FIRST_SERVICE_DT,
    MAX(C.CLAIM_FIRST_SERVICE_DT) AS LATEST_SERVICE_DT,
    COUNT_IF(C.LINE_PAID_AMT IS NULL) AS NULL_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT = 0) AS ZERO_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT < 0) AS NEGATIVE_PAID_LINES,
    COUNT_IF(C.LINE_PAID_AMT > 0) AS POSITIVE_PAID_LINES,
    SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT,
    SUM(C.LINE_ALLOW_AMT) AS ALLOWED_AMOUNT,
    SUM(C.LINE_BILL_AMT) AS BILLED_AMOUNT,
    SUM(C.LINE_ENCOUNTER_PAID_AMT) AS ENCOUNTER_PAID_AMOUNT
FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
  AND C.CLAIM_STATUS_CD IN ('P', 'D')
  AND C.CLAIM_VOID_IND = 'N'
  AND C.LAST_CLAIM_IND = 'Y'
GROUP BY C.PROCEDURE_CD, C.CLAIM_STATUS_CD, C.CLAIM_TYPE_CD
ORDER BY C.CLAIM_STATUS_CD, PAID_AMOUNT DESC NULLS LAST, C.PROCEDURE_CD, C.CLAIM_TYPE_CD;

-- 4 -> 04_dental_examples.csv (OPTIONAL)
-- At most 100 selected examples per status: one per observed type/procedure combination.
-- Type/code ordering and the per-status cap can omit combinations; use statement 3
-- for actual population coverage. No beneficiary, ICN, NPI or provider IDs are exported.
-- This deliberately projects only known shared fields, not SELECT * from claim rows.
WITH examples AS (
    SELECT
        C.CLAIM_STATUS_CD,
        C.CLAIM_TYPE_CD,
        C.CLAIM_TYPE_DESC,
        C.PROCEDURE_CD,
        C.CLAIM_FIRST_SERVICE_DT,
        C.CLAIM_PAID_DT,
        C.LINE_PAID_AMT,
        C.LINE_ALLOW_AMT,
        C.LINE_BILL_AMT,
        C.LINE_ENCOUNTER_PAID_AMT,
        C.LINE_ENCOUNTER_ALLOW_AMT,
        C.LINE_CO_PAY_AMT
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P', 'D')
      AND C.CLAIM_VOID_IND = 'N'
      AND C.LAST_CLAIM_IND = 'Y'
    QUALIFY ROW_NUMBER() OVER (
        PARTITION BY C.CLAIM_STATUS_CD, C.CLAIM_TYPE_CD, C.PROCEDURE_CD
        ORDER BY C.CLAIM_FIRST_SERVICE_DT DESC NULLS LAST,
                 C.CLAIM_PAID_DT DESC NULLS LAST,
                 C.CLAIM_ICN_NBR, C.CLAIM_LINE_NBR
    ) = 1
)
SELECT *
FROM examples
QUALIFY ROW_NUMBER() OVER (
    PARTITION BY CLAIM_STATUS_CD ORDER BY CLAIM_TYPE_CD, PROCEDURE_CD
) <= 100
ORDER BY CLAIM_STATUS_CD, CLAIM_TYPE_CD, PROCEDURE_CD
;
