-- Run AFTER compiling TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV.
-- Read-only live source-versus-model comparisons; no frozen-dollar expectations.
-- Queries declared Dental metrics and dimensions through SEMANTIC_VIEW.
-- Direct SQL has no agent-implied period/status defaults: each scope is explicit.
-- Each statement returns PASS only when its checked values agree. Empty source = REVIEW.
-- No beneficiary or provider identifiers are returned.

-- 1 -> 17_semantic_baseline.csv
WITH source_rows AS (
    SELECT * FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
), expected AS (
    SELECT COUNT(*) AS LINES, COUNT(DISTINCT CLAIM_ICN_NBR) AS CLAIMS,
           COUNT(DISTINCT BENEFICIARY_ID) AS MEMBERS,
           SUM(LINE_PAID_AMT) AS PAID_AMOUNT,
           COUNT_IF(LINE_STATUS_CD = 'P') AS PAID_LINES,
           COUNT_IF(LINE_STATUS_CD = 'D') AS DENIED_LINES,
           COUNT_IF(CLAIM_STATUS_CD = 'P') AS LINES_ON_PAID_CLAIMS,
           COUNT_IF(LINE_STATUS_CD = 'D') / NULLIF(COUNT_IF(LINE_STATUS_CD IN ('P','D')),0) AS LINE_DENIAL_RATE,
           COUNT_IF(CLAIM_STATUS_CD = 'D') / NULLIF(COUNT_IF(CLAIM_STATUS_CD IN ('P','D')),0) AS HEADER_DENIED_LINE_SHARE
    FROM source_rows
), actual AS (
    SELECT * FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM AS CLAIMS,
                DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_BENEFICIARY AS MEMBERS,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT,
                DENTAL_CLAIM_LINE_FACT.COUNT_PAID_CLAIM_LINE AS PAID_LINES,
                DENTAL_CLAIM_LINE_FACT.COUNT_DENIED_CLAIM_LINE AS DENIED_LINES,
                DENTAL_CLAIM_LINE_FACT.COUNT_LINES_ON_PAID_CLAIMS AS LINES_ON_PAID_CLAIMS,
                DENTAL_CLAIM_LINE_FACT.DENIED_CLAIM_LINE_RATE AS LINE_DENIAL_RATE,
                DENTAL_CLAIM_LINE_FACT.DENIED_HEADER_LINE_SHARE AS HEADER_DENIED_LINE_SHARE
    )
)
SELECT E.LINES AS SOURCE_LINES, A.LINES AS SEMANTIC_LINES,
       A.LINES-E.LINES AS LINE_DIFFERENCE,
       A.CLAIMS-E.CLAIMS AS CLAIM_DIFFERENCE,
       A.MEMBERS-E.MEMBERS AS MEMBER_DIFFERENCE,
       E.PAID_AMOUNT AS SOURCE_PAID_AMOUNT, A.PAID_AMOUNT AS SEMANTIC_PAID_AMOUNT,
       A.PAID_AMOUNT-E.PAID_AMOUNT AS PAID_DIFFERENCE,
       A.PAID_LINES-E.PAID_LINES AS PAID_LINE_DIFFERENCE,
       A.DENIED_LINES-E.DENIED_LINES AS DENIED_LINE_DIFFERENCE,
       A.LINES_ON_PAID_CLAIMS-E.LINES_ON_PAID_CLAIMS AS HEADER_PAID_LINE_DIFFERENCE,
       E.LINE_DENIAL_RATE AS SOURCE_LINE_DENIAL_RATE, A.LINE_DENIAL_RATE AS SEMANTIC_LINE_DENIAL_RATE,
       E.HEADER_DENIED_LINE_SHARE AS SOURCE_HEADER_DENIED_LINE_SHARE,
       A.HEADER_DENIED_LINE_SHARE AS SEMANTIC_HEADER_DENIED_LINE_SHARE,
       CASE WHEN E.LINES = 0 THEN 'REVIEW: empty source'
            WHEN A.LINES = E.LINES AND A.CLAIMS = E.CLAIMS AND A.MEMBERS = E.MEMBERS
             AND A.PAID_AMOUNT = E.PAID_AMOUNT AND A.PAID_LINES = E.PAID_LINES
             AND A.DENIED_LINES = E.DENIED_LINES
             AND A.LINES_ON_PAID_CLAIMS = E.LINES_ON_PAID_CLAIMS
             AND EQUAL_NULL(A.LINE_DENIAL_RATE,E.LINE_DENIAL_RATE)
             AND EQUAL_NULL(A.HEADER_DENIED_LINE_SHARE,E.HEADER_DENIED_LINE_SHARE) THEN 'PASS'
            ELSE 'FAIL' END AS TEST_RESULT
FROM expected E CROSS JOIN actual A;

-- 2 -> 18_semantic_status.csv
-- Specifically protects denied details on paid claims and true line denial logic.
WITH expected AS (
    SELECT C.CLAIM_STATUS_CD AS HEADER_STATUS, C.LINE_STATUS_CD AS DETAIL_STATUS,
           COUNT(*) AS LINES, SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
    GROUP BY C.CLAIM_STATUS_CD, C.LINE_STATUS_CD
), actual AS (
    SELECT * FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS DENTAL_CLAIM_LINE_FACT.CLAIM_STATUS_CD AS HEADER_STATUS,
                   DENTAL_CLAIM_LINE_FACT.LINE_STATUS_CD AS DETAIL_STATUS
    )
)
SELECT COALESCE(E.HEADER_STATUS,A.HEADER_STATUS) AS HEADER_STATUS,
       COALESCE(E.DETAIL_STATUS,A.DETAIL_STATUS) AS DETAIL_STATUS,
       E.LINES AS SOURCE_LINES, A.LINES AS SEMANTIC_LINES,
       E.PAID_AMOUNT AS SOURCE_PAID_AMOUNT, A.PAID_AMOUNT AS SEMANTIC_PAID_AMOUNT,
       CASE WHEN E.LINES = A.LINES AND E.PAID_AMOUNT = A.PAID_AMOUNT THEN 'PASS'
            ELSE 'FAIL' END AS TEST_RESULT
FROM expected E FULL OUTER JOIN actual A
  ON E.HEADER_STATUS = A.HEADER_STATUS
 AND (E.DETAIL_STATUS = A.DETAIL_STATUS OR (E.DETAIL_STATUS IS NULL AND A.DETAIL_STATUS IS NULL))
ORDER BY HEADER_STATUS, DETAIL_STATUS;

-- 3 -> 19_semantic_join_retention.csv
-- Attribute breakouts must preserve source totals, including unknown plan/profile rows.
-- These sum additive line/dollar metrics only, never group-level distinct members/ICNs.
WITH expected AS (
    SELECT COUNT(*) AS LINES, SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
), by_role AS (
    SELECT 'Billing provider' AS REFERENCE_ROLE, SUM(LINES) AS LINES, SUM(PAID_AMOUNT) AS PAID_AMOUNT
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS BILLING_PROVLOC_DIM.BILLING_PROVIDER_NM
    )
    UNION ALL
    SELECT 'Rendering provider', SUM(LINES), SUM(PAID_AMOUNT)
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS RENDERING_PROVLOC_DIM.RENDERING_PROVIDER_NM
    )
    UNION ALL
    SELECT 'Claim-recorded plan', SUM(LINES), SUM(PAID_AMOUNT)
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS DENTAL_CLAIM_LINE_FACT.CLAIM_HEALTH_PLAN_ID,
                   CLAIM_PLAN_DIM.CLAIM_PLAN_DESC
    )
    UNION ALL
    SELECT 'Operative assigned plan', SUM(LINES), SUM(PAID_AMOUNT)
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS HEALTH_PLAN_DIM.HEALTH_PLAN_DESC
    )
    UNION ALL
    SELECT 'Profile residence county', SUM(LINES), SUM(PAID_AMOUNT)
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS BENEFICIARY_COUNTY_DIM.BENEFICIARY_COUNTY_NM
    )
    UNION ALL
    SELECT 'Claim organization', SUM(LINES), SUM(PAID_AMOUNT)
    FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS MCO_DIM.MCO_NM
    )
)
SELECT A.REFERENCE_ROLE, E.LINES AS SOURCE_LINES, A.LINES AS SEMANTIC_LINES,
       A.LINES-E.LINES AS LINE_DIFFERENCE,
       E.PAID_AMOUNT AS SOURCE_PAID_AMOUNT, A.PAID_AMOUNT AS SEMANTIC_PAID_AMOUNT,
       A.PAID_AMOUNT-E.PAID_AMOUNT AS PAID_DIFFERENCE,
       CASE WHEN E.LINES = 0 THEN 'REVIEW: empty source'
            WHEN E.LINES = A.LINES AND E.PAID_AMOUNT = A.PAID_AMOUNT THEN 'PASS'
            ELSE 'FAIL' END AS TEST_RESULT
FROM by_role A CROSS JOIN expected E
ORDER BY A.REFERENCE_ROLE;

-- 4 -> 20_semantic_procedure_units.csv
-- Quantity/dollars stay grouped by raw procedure; no clinical crosswalk is inferred.
WITH expected AS (
    SELECT C.CLAIM_STATUS_CD AS HEADER_STATUS, C.PROCEDURE_CD AS CODE,
           COUNT(*) AS LINES, SUM(C.LINE_PAID_AMT) AS PAID_AMOUNT,
           SUM(C.BILL_QTY) AS BILLED_UNITS, SUM(C.ALLOW_QTY) AS ALLOWED_UNITS
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
    GROUP BY C.CLAIM_STATUS_CD, C.PROCEDURE_CD
), actual AS (
    SELECT * FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT,
                DENTAL_CLAIM_LINE_FACT.SUM_BILLED_SERVICE_QTY AS BILLED_UNITS,
                DENTAL_CLAIM_LINE_FACT.SUM_ALLOWED_SERVICE_QTY AS ALLOWED_UNITS
        DIMENSIONS DENTAL_CLAIM_LINE_FACT.CLAIM_STATUS_CD AS HEADER_STATUS,
                   DENTAL_CLAIM_LINE_FACT.PROCEDURE_CD AS CODE
    )
)
SELECT COALESCE(E.HEADER_STATUS,A.HEADER_STATUS) AS HEADER_STATUS,
       COALESCE(E.CODE,A.CODE) AS PROCEDURE_CD,
       E.LINES AS SOURCE_LINES, A.LINES AS SEMANTIC_LINES,
       E.PAID_AMOUNT AS SOURCE_PAID_AMOUNT, A.PAID_AMOUNT AS SEMANTIC_PAID_AMOUNT,
       E.BILLED_UNITS AS SOURCE_BILLED_UNITS, A.BILLED_UNITS AS SEMANTIC_BILLED_UNITS,
       E.ALLOWED_UNITS AS SOURCE_ALLOWED_UNITS, A.ALLOWED_UNITS AS SEMANTIC_ALLOWED_UNITS,
       CASE WHEN E.LINES = A.LINES AND E.PAID_AMOUNT = A.PAID_AMOUNT
             AND EQUAL_NULL(E.BILLED_UNITS,A.BILLED_UNITS)
             AND EQUAL_NULL(E.ALLOWED_UNITS,A.ALLOWED_UNITS) THEN 'PASS'
            ELSE 'FAIL' END AS TEST_RESULT
FROM expected E FULL OUTER JOIN actual A
  ON E.HEADER_STATUS = A.HEADER_STATUS AND EQUAL_NULL(E.CODE,A.CODE)
ORDER BY HEADER_STATUS, PROCEDURE_CD;

-- 5 -> 21_semantic_age.csv
-- Independent source band uses the 21st birthday boundary, not the model's year formula.
-- Unknown includes missing dates/DOB and service dates before DOB. No PMPM join.
WITH source_rows AS (
    SELECT C.CLAIM_STATUS_CD AS HEADER_STATUS, C.LINE_PAID_AMT,
           CASE WHEN C.BENEFICIARY_BIRTH_DT IS NULL OR C.CLAIM_FIRST_SERVICE_DT IS NULL
                      OR C.CLAIM_FIRST_SERVICE_DT < C.BENEFICIARY_BIRTH_DT THEN 'Unknown/invalid'
                WHEN C.CLAIM_FIRST_SERVICE_DT < DATEADD(YEAR,21,C.BENEFICIARY_BIRTH_DT) THEN '0-20'
                ELSE '21+' END AS AGE_BAND
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
), expected AS (
    SELECT HEADER_STATUS, AGE_BAND, COUNT(*) AS LINES, SUM(LINE_PAID_AMT) AS PAID_AMOUNT
    FROM source_rows GROUP BY HEADER_STATUS, AGE_BAND
), semantic_ages AS (
    SELECT * FROM SEMANTIC_VIEW(
        TRN__TN_DE.SBX_ETL.DENTAL_CLAIMS_SV
        METRICS DENTAL_CLAIM_LINE_FACT.COUNT_CLAIM_LINE AS LINES,
                DENTAL_CLAIM_LINE_FACT.SUM_LINE_PAID_AMT AS PAID_AMOUNT
        DIMENSIONS DENTAL_CLAIM_LINE_FACT.CLAIM_STATUS_CD AS HEADER_STATUS,
                   DENTAL_CLAIM_LINE_FACT.AGE_AT_SERVICE_NBR AS AGE_YEARS
    )
), actual AS (
    SELECT HEADER_STATUS,
           CASE WHEN AGE_YEARS IS NULL OR AGE_YEARS < 0 THEN 'Unknown/invalid'
                WHEN AGE_YEARS < 21 THEN '0-20' ELSE '21+' END AS AGE_BAND,
           SUM(LINES) AS LINES, SUM(PAID_AMOUNT) AS PAID_AMOUNT
    FROM semantic_ages GROUP BY HEADER_STATUS, AGE_BAND
)
SELECT COALESCE(E.HEADER_STATUS,A.HEADER_STATUS) AS HEADER_STATUS,
       COALESCE(E.AGE_BAND,A.AGE_BAND) AS AGE_BAND,
       E.LINES AS SOURCE_LINES, A.LINES AS SEMANTIC_LINES,
       E.PAID_AMOUNT AS SOURCE_PAID_AMOUNT, A.PAID_AMOUNT AS SEMANTIC_PAID_AMOUNT,
       CASE WHEN E.LINES = A.LINES AND E.PAID_AMOUNT = A.PAID_AMOUNT THEN 'PASS'
            ELSE 'FAIL' END AS TEST_RESULT
FROM expected E FULL OUTER JOIN actual A
  ON E.HEADER_STATUS = A.HEADER_STATUS AND E.AGE_BAND = A.AGE_BAND
ORDER BY HEADER_STATUS, AGE_BAND;
