-- Remaining pre-deployment gate: current reference key uniqueness and join coverage.
-- Read-only; no INFORMATION_SCHEMA, created objects, or additional source discovery.
-- Run all three statements and retain each result. Query 1 must be reviewed before
-- trusting the declared UNIQUE keys. Diagnostic grouping does not deduplicate the model.

-- 1 -> 14_reference_keys.csv
WITH reference_keys AS (
    SELECT 'Provider/location' AS REFERENCE_ROLE,
           COUNT(*) AS ROWS_PER_KEY,
           IFF(MMIS_PROVIDER_ID IS NULL OR MMIS_PROVLOC_ID IS NULL, 1, 0) AS NULL_KEY
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.MMIS_PROVLOC_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY MMIS_PROVIDER_ID, MMIS_PROVLOC_ID
    UNION ALL
    SELECT 'Health plan', COUNT(*), IFF(HEALTH_PLAN_ID IS NULL, 1, 0)
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.HEALTH_PLAN_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY HEALTH_PLAN_ID
    UNION ALL
    SELECT 'Beneficiary', COUNT(*), IFF(BENEFICIARY_ID IS NULL, 1, 0)
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.BENEFICIARY_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY BENEFICIARY_ID
    UNION ALL
    SELECT 'Date', COUNT(*), IFF(CALENDAR_DT IS NULL, 1, 0)
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.DATE_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY CALENDAR_DT
    UNION ALL
    SELECT 'County', COUNT(*), IFF(COUNTY_CD IS NULL, 1, 0)
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.COUNTY_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY COUNTY_CD
    UNION ALL
    SELECT 'Claim organization', COUNT(*), IFF(MCO_ID IS NULL, 1, 0)
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.MCO_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY MCO_ID
)
SELECT REFERENCE_ROLE, SUM(ROWS_PER_KEY) AS CURRENT_REFERENCE_ROWS,
       COUNT(*) AS DISTINCT_KEYS,
       COUNT_IF(ROWS_PER_KEY > 1) AS DUPLICATE_KEY_GROUPS,
       SUM(ROWS_PER_KEY - 1) AS EXCESS_ROWS,
       SUM(IFF(NULL_KEY = 1, ROWS_PER_KEY, 0)) AS NULL_KEY_ROWS
FROM reference_keys
GROUP BY REFERENCE_ROLE
ORDER BY REFERENCE_ROLE;

-- 2 -> 15_role_join_coverage.csv
-- Match-count relations are diagnostics only. Their counts predict direct LEFT JOIN
-- fanout without multiplying the test rows. Expected single-join extra rows = 0.
WITH dental AS (
    SELECT * FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P', 'D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
), provider_keys AS (
    SELECT MMIS_PROVIDER_ID, MMIS_PROVLOC_ID, COUNT(*) AS MATCHES
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.MMIS_PROVLOC_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY MMIS_PROVIDER_ID, MMIS_PROVLOC_ID
), plan_keys AS (
    SELECT HEALTH_PLAN_ID, COUNT(*) AS MATCHES
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.HEALTH_PLAN_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY HEALTH_PLAN_ID
), organization_keys AS (
    SELECT MCO_ID, COUNT(*) AS MATCHES
    FROM (SELECT * FROM TRN__TN_DE.MART_EDW_SV.MCO_DIM WHERE DE_CURRENT_ROW_IND = 'Y')
    GROUP BY MCO_ID
), role_matches AS (
    SELECT 'Billing provider/location' AS REFERENCE_ROLE, D.CLAIM_STATUS_CD,
           D.LINE_PAID_AMT, COALESCE(K.MATCHES, 0) AS MATCHES
    FROM dental D LEFT JOIN provider_keys K
      ON D.BILL_MMIS_PROVIDER_ID = K.MMIS_PROVIDER_ID AND D.BILL_MMIS_PROVLOC_ID = K.MMIS_PROVLOC_ID
    UNION ALL
    SELECT 'Rendering provider/location', D.CLAIM_STATUS_CD, D.LINE_PAID_AMT, COALESCE(K.MATCHES, 0)
    FROM dental D LEFT JOIN provider_keys K
      ON D.RENDER_MMIS_PROVIDER_ID = K.MMIS_PROVIDER_ID AND D.RENDER_MMIS_PROVLOC_ID = K.MMIS_PROVLOC_ID
    UNION ALL
    SELECT 'Claim-recorded plan', D.CLAIM_STATUS_CD, D.LINE_PAID_AMT, COALESCE(K.MATCHES, 0)
    FROM dental D LEFT JOIN plan_keys K ON D.HEALTH_PLAN_ID = K.HEALTH_PLAN_ID
    UNION ALL
    SELECT 'Claim organization', D.CLAIM_STATUS_CD, D.LINE_PAID_AMT, COALESCE(K.MATCHES, 0)
    FROM dental D LEFT JOIN organization_keys K ON D.MCO_ID = K.MCO_ID
)
SELECT REFERENCE_ROLE, CLAIM_STATUS_CD, COUNT(*) AS BASELINE_LINES,
       SUM(LINE_PAID_AMT) AS BASELINE_PAID_AMOUNT,
       COUNT_IF(MATCHES = 0) AS UNMATCHED_LINES,
       SUM(IFF(MATCHES = 0, LINE_PAID_AMT, 0)) AS UNMATCHED_PAID_AMOUNT,
       COUNT_IF(MATCHES > 1) AS FANOUT_SOURCE_LINES,
       SUM(GREATEST(MATCHES, 1) - 1) AS PREDICTED_LEFT_JOIN_EXTRA_ROWS,
       SUM(LINE_PAID_AMT * GREATEST(MATCHES, 1)) AS PREDICTED_LEFT_JOIN_PAID_AMOUNT
FROM role_matches
GROUP BY REFERENCE_ROLE, CLAIM_STATUS_CD
ORDER BY REFERENCE_ROLE, CLAIM_STATUS_CD;

-- 3 -> 16_profile_coverage.csv
-- Reproduces the model's selected operative profile at CLAIM_FIRST_SERVICE_DT.
-- This is a candidate coverage/tie diagnostic, not proof of dental entitlement.
WITH dental AS (
    SELECT * FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P', 'D')
      AND C.CLAIM_VOID_IND = 'N' AND C.LAST_CLAIM_IND = 'Y'
), member_dates AS (
    SELECT DISTINCT BENEFICIARY_ID, CLAIM_FIRST_SERVICE_DT FROM dental
), candidates AS (
    SELECT D.BENEFICIARY_ID, D.CLAIM_FIRST_SERVICE_DT,
           P.HIER_NBR, P.HEALTH_PLAN_ID,
           DENSE_RANK() OVER (
               PARTITION BY D.BENEFICIARY_ID, D.CLAIM_FIRST_SERVICE_DT
               ORDER BY P.HIER_NBR, P.HEALTH_PLAN_ID
           ) AS CANDIDATE_RANK
    FROM member_dates D
    JOIN (SELECT * FROM TRN__TN_DE.MART_EDW_SV.DATE_DIM WHERE DE_CURRENT_ROW_IND = 'Y') DT
      ON D.CLAIM_FIRST_SERVICE_DT = DT.CALENDAR_DT
    JOIN TRN__TN_DE.MART_EDW_SV.BENEFICIARY_ELIGIBILITY_PER_MEMBER_PER_MONTH P
      ON D.BENEFICIARY_ID = P.BENEFICIARY_ID
      AND DT.YR_MONTH_NBR = P.BENEFICIARY_ELIGIBILITY_YR_MONTH
      AND D.CLAIM_FIRST_SERVICE_DT BETWEEN P.ELIGIBILITY_BEGIN_DT AND P.ELIGIBILITY_END_DT
    JOIN (SELECT * FROM TRN__TN_DE.MART_EDW_SV.BENEFICIARY_DIM WHERE DE_CURRENT_ROW_IND = 'Y') B
      ON D.BENEFICIARY_ID = B.BENEFICIARY_ID
    JOIN (SELECT * FROM TRN__TN_DE.MART_EDW_SV.HEALTH_PLAN_DIM WHERE DE_CURRENT_ROW_IND = 'Y') H
      ON P.HEALTH_PLAN_ID = H.HEALTH_PLAN_ID
), candidate_counts AS (
    SELECT BENEFICIARY_ID, CLAIM_FIRST_SERVICE_DT,
           COUNT(*) AS CANDIDATE_COUNT,
           COUNT_IF(CANDIDATE_RANK = 1) AS FIRST_ORDER_TIES
    FROM candidates
    GROUP BY BENEFICIARY_ID, CLAIM_FIRST_SERVICE_DT
)
SELECT D.CLAIM_STATUS_CD, COUNT(*) AS BASELINE_LINES,
       SUM(D.LINE_PAID_AMT) AS BASELINE_PAID_AMOUNT,
       COUNT_IF(C.CANDIDATE_COUNT IS NULL) AS NO_PROFILE_LINES,
       SUM(IFF(C.CANDIDATE_COUNT IS NULL, D.LINE_PAID_AMT, 0)) AS NO_PROFILE_PAID_AMOUNT,
       COUNT_IF(C.CANDIDATE_COUNT > 1) AS MULTIPLE_CANDIDATE_LINES,
       COUNT_IF(C.FIRST_ORDER_TIES > 1) AS TIED_FIRST_ORDER_LINES,
       COUNT(*) AS LEFT_JOIN_LINES,
       SUM(D.LINE_PAID_AMT) AS LEFT_JOIN_PAID_AMOUNT
FROM dental D
LEFT JOIN candidate_counts C
  ON D.BENEFICIARY_ID = C.BENEFICIARY_ID AND D.CLAIM_FIRST_SERVICE_DT = C.CLAIM_FIRST_SERVICE_DT
GROUP BY D.CLAIM_STATUS_CD
ORDER BY D.CLAIM_STATUS_CD;
