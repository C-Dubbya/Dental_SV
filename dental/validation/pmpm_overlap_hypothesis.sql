-- Hypothesis: Dental and PMPM periods overlap, but sample member/date records
-- are missing; profile failures are not primarily caused by reference joins.
-- One read-only statement. Export as 22_pmpm_overlap_hypothesis.csv.
-- Physical sources only; no semantic deployment, INFORMATION_SCHEMA or temp objects.
-- Uses CLAIM_FIRST_SERVICE_DT, matching the current beneficiary-profile anchor.
-- No nearby-month fallback, eligibility widening or population exclusion is introduced.

WITH dental AS (
    SELECT C.CLAIM_ICN_NBR, C.CLAIM_LINE_NBR, C.BENEFICIARY_ID,
           C.CLAIM_STATUS_CD, C.CLAIM_FIRST_SERVICE_DT, C.LINE_PAID_AMT
    FROM TRN__TN_DE.MART_EDW_SV.CLAIM_LINE_TFACT C
    WHERE UPPER(TRIM(C.CLAIM_CATEGORY_CD)) = 'DENTAL'
      AND C.CLAIM_STATUS_CD IN ('P','D')
      AND C.CLAIM_VOID_IND = 'N'
      AND C.LAST_CLAIM_IND = 'Y'
), pmpm AS (
    SELECT BENEFICIARY_ID,
           TRY_TO_NUMBER(TO_VARCHAR(BENEFICIARY_ELIGIBILITY_YR_MONTH)) AS PMPM_YR_MONTH,
           ELIGIBILITY_BEGIN_DT, ELIGIBILITY_END_DT, HEALTH_PLAN_ID
    FROM TRN__TN_DE.MART_EDW_SV.BENEFICIARY_ELIGIBILITY_PER_MEMBER_PER_MONTH
    -- Historical source: do not impose a current-row, plan, program or dual filter.
), pmpm_members AS (
    SELECT BENEFICIARY_ID, COUNT(*) AS MEMBER_ROWS
    FROM pmpm GROUP BY BENEFICIARY_ID
), pmpm_months AS (
    SELECT PMPM_YR_MONTH, COUNT(*) AS GLOBAL_MONTH_ROWS
    FROM pmpm GROUP BY PMPM_YR_MONTH
), current_dates AS (
    SELECT CALENDAR_DT, COUNT(*) AS DATE_REFERENCE_ROWS,
           MIN(TRY_TO_NUMBER(TO_VARCHAR(YR_MONTH_NBR))) AS DIM_YR_MONTH
    FROM (
        SELECT * FROM TRN__TN_DE.MART_EDW_SV.DATE_DIM
        WHERE DE_CURRENT_ROW_IND = 'Y'
    )
    GROUP BY CALENDAR_DT
), current_members AS (
    SELECT BENEFICIARY_ID, COUNT(*) AS MEMBER_REFERENCE_ROWS
    FROM (
        SELECT * FROM TRN__TN_DE.MART_EDW_SV.BENEFICIARY_DIM
        WHERE DE_CURRENT_ROW_IND = 'Y'
    )
    GROUP BY BENEFICIARY_ID
), current_plans AS (
    SELECT HEALTH_PLAN_ID, COUNT(*) AS PLAN_REFERENCE_ROWS
    FROM (
        SELECT * FROM TRN__TN_DE.MART_EDW_SV.HEALTH_PLAN_DIM
        WHERE DE_CURRENT_ROW_IND = 'Y'
    )
    GROUP BY HEALTH_PLAN_ID
), member_dates AS (
    SELECT DISTINCT BENEFICIARY_ID, CLAIM_FIRST_SERVICE_DT,
           TO_NUMBER(TO_CHAR(CLAIM_FIRST_SERVICE_DT, 'YYYYMM')) AS SERVICE_YR_MONTH
    FROM dental
), date_context AS (
    SELECT K.*,
           COALESCE(D.DATE_REFERENCE_ROWS,0) AS DATE_REFERENCE_ROWS,
           D.DIM_YR_MONTH,
           COALESCE(B.MEMBER_REFERENCE_ROWS,0) AS MEMBER_REFERENCE_ROWS,
           COALESCE(M.MEMBER_ROWS,0) AS PMPM_MEMBER_ROWS,
           COALESCE(G.GLOBAL_MONTH_ROWS,0) AS PMPM_GLOBAL_MONTH_ROWS
    FROM member_dates K
    LEFT JOIN current_dates D ON K.CLAIM_FIRST_SERVICE_DT = D.CALENDAR_DT
    LEFT JOIN current_members B ON K.BENEFICIARY_ID = B.BENEFICIARY_ID
    LEFT JOIN pmpm_members M ON K.BENEFICIARY_ID = M.BENEFICIARY_ID
    LEFT JOIN pmpm_months G ON K.SERVICE_YR_MONTH = G.PMPM_YR_MONTH
), matching_counts AS (
    -- Collapse PMPM candidates at member/date BEFORE rejoining claim lines.
    -- Calendar-month checks are independent of DATE_DIM so a missing date key
    -- cannot masquerade as a missing PMPM member-month.
    SELECT K.BENEFICIARY_ID, K.CLAIM_FIRST_SERVICE_DT,
           COALESCE(COUNT_IF(P.PMPM_YR_MONTH = K.SERVICE_YR_MONTH),0) AS MEMBER_MONTH_ROWS,
           COALESCE(COUNT_IF(
               P.PMPM_YR_MONTH = K.SERVICE_YR_MONTH
               AND (P.ELIGIBILITY_BEGIN_DT IS NULL OR P.ELIGIBILITY_END_DT IS NULL
                    OR P.ELIGIBILITY_BEGIN_DT > P.ELIGIBILITY_END_DT)
           ),0) AS INVALID_MEMBER_MONTH_SPANS,
           COALESCE(COUNT_IF(
               P.PMPM_YR_MONTH = K.SERVICE_YR_MONTH
               AND K.CLAIM_FIRST_SERVICE_DT BETWEEN P.ELIGIBILITY_BEGIN_DT AND P.ELIGIBILITY_END_DT
           ),0) AS COVERING_MEMBER_MONTH_ROWS,
           COALESCE(COUNT_IF(
               P.PMPM_YR_MONTH = K.SERVICE_YR_MONTH
               AND K.CLAIM_FIRST_SERVICE_DT BETWEEN P.ELIGIBILITY_BEGIN_DT AND P.ELIGIBILITY_END_DT
               AND H.PLAN_REFERENCE_ROWS > 0
           ),0) AS COVERING_ROWS_WITH_CURRENT_PLAN,
           COALESCE(COUNT_IF(
               K.DATE_REFERENCE_ROWS > 0 AND K.MEMBER_REFERENCE_ROWS > 0
               AND P.PMPM_YR_MONTH = K.DIM_YR_MONTH
               AND K.CLAIM_FIRST_SERVICE_DT BETWEEN P.ELIGIBILITY_BEGIN_DT AND P.ELIGIBILITY_END_DT
               AND H.PLAN_REFERENCE_ROWS > 0
           ),0) AS FULL_PROFILE_CANDIDATES
    FROM date_context K
    LEFT JOIN pmpm P
      ON K.BENEFICIARY_ID = P.BENEFICIARY_ID
     AND (P.PMPM_YR_MONTH = K.SERVICE_YR_MONTH OR P.PMPM_YR_MONTH = K.DIM_YR_MONTH)
    LEFT JOIN current_plans H ON P.HEALTH_PLAN_ID = H.HEALTH_PLAN_ID
    GROUP BY K.BENEFICIARY_ID, K.CLAIM_FIRST_SERVICE_DT
), classified_dates AS (
    SELECT K.*, C.MEMBER_MONTH_ROWS, C.COVERING_MEMBER_MONTH_ROWS,
           C.COVERING_ROWS_WITH_CURRENT_PLAN, C.FULL_PROFILE_CANDIDATES,
           IFF(C.FULL_PROFILE_CANDIDATES > 0, 'Matched', 'No profile') AS PROFILE_MATCH,
           CASE
             WHEN C.FULL_PROFILE_CANDIDATES > 0 THEN '00 Matching profile candidate exists'
             WHEN K.BENEFICIARY_ID IS NULL THEN '01 Missing claim member key'
             WHEN K.CLAIM_FIRST_SERVICE_DT IS NULL THEN '02 Missing claim service date'
             WHEN K.DATE_REFERENCE_ROWS = 0 THEN '03 Missing current DATE_DIM service date'
             WHEN K.DIM_YR_MONTH IS NULL OR K.DIM_YR_MONTH <> K.SERVICE_YR_MONTH
               THEN '04 DATE_DIM month missing or disagrees with calendar'
             WHEN K.PMPM_MEMBER_ROWS = 0 THEN '05 Member absent from all PMPM sample rows'
             WHEN K.PMPM_GLOBAL_MONTH_ROWS = 0 THEN '06 Service month absent from all PMPM sample rows'
             WHEN C.MEMBER_MONTH_ROWS = 0 THEN '07 Member exists, but no PMPM row for service month'
             WHEN C.COVERING_MEMBER_MONTH_ROWS = 0
                  AND C.INVALID_MEMBER_MONTH_SPANS = C.MEMBER_MONTH_ROWS
               THEN '08 Member-month rows have only null or reversed spans'
             WHEN C.COVERING_MEMBER_MONTH_ROWS = 0
               THEN '09 Member-month exists, service date outside its spans'
             WHEN K.MEMBER_REFERENCE_ROWS = 0 THEN '10 Covering PMPM row, missing current beneficiary'
             WHEN C.COVERING_ROWS_WITH_CURRENT_PLAN = 0
               THEN '11 Covering PMPM row, missing current health plan'
             ELSE '12 Unexpected unmatched combination; review'
           END AS MATCH_REASON
    FROM date_context K
    JOIN matching_counts C
      ON (K.BENEFICIARY_ID = C.BENEFICIARY_ID
          OR (K.BENEFICIARY_ID IS NULL AND C.BENEFICIARY_ID IS NULL))
     AND (K.CLAIM_FIRST_SERVICE_DT = C.CLAIM_FIRST_SERVICE_DT
          OR (K.CLAIM_FIRST_SERVICE_DT IS NULL AND C.CLAIM_FIRST_SERVICE_DT IS NULL))
), claim_bounds AS (
    SELECT MIN(CLAIM_FIRST_SERVICE_DT) AS CLAIM_MIN_SERVICE_DT,
           MAX(CLAIM_FIRST_SERVICE_DT) AS CLAIM_MAX_SERVICE_DT
    FROM dental
), pmpm_bounds AS (
    SELECT MIN(PMPM_YR_MONTH) AS PMPM_MIN_YR_MONTH,
           MAX(PMPM_YR_MONTH) AS PMPM_MAX_YR_MONTH,
           MIN(IFF(ELIGIBILITY_BEGIN_DT <= ELIGIBILITY_END_DT, ELIGIBILITY_BEGIN_DT, NULL)) AS PMPM_MIN_VALID_BEGIN_DT,
           MAX(IFF(ELIGIBILITY_BEGIN_DT <= ELIGIBILITY_END_DT, ELIGIBILITY_END_DT, NULL)) AS PMPM_MAX_VALID_END_DT,
           COUNT(*) AS PMPM_SOURCE_ROWS,
           COALESCE(COUNT_IF(PMPM_YR_MONTH IS NULL),0) AS PMPM_UNPARSEABLE_OR_NULL_MONTH_ROWS
    FROM pmpm
), reason_totals AS (
    SELECT D.CLAIM_STATUS_CD, K.PROFILE_MATCH, K.MATCH_REASON,
           COUNT(*) AS CLAIM_LINE_COUNT,
           COUNT(DISTINCT D.CLAIM_ICN_NBR) AS CLAIM_COUNT,
           COUNT(DISTINCT D.BENEFICIARY_ID) AS MEMBER_COUNT,
           COUNT(DISTINCT D.BENEFICIARY_ID,D.CLAIM_FIRST_SERVICE_DT) AS MEMBER_SERVICE_DATES,
           SUM(D.LINE_PAID_AMT) AS PAID_AMOUNT,
           MIN(D.CLAIM_FIRST_SERVICE_DT) AS REASON_FIRST_SERVICE_DT,
           MAX(D.CLAIM_FIRST_SERVICE_DT) AS REASON_LATEST_SERVICE_DT,
           COALESCE(COUNT_IF(K.PMPM_MEMBER_ROWS > 0),0) AS LINES_WITH_MEMBER_ANYWHERE_IN_PMPM,
           COALESCE(COUNT_IF(K.PMPM_GLOBAL_MONTH_ROWS > 0),0) AS LINES_WITH_SERVICE_MONTH_IN_PMPM,
           COALESCE(COUNT_IF(K.MEMBER_MONTH_ROWS > 0),0) AS LINES_WITH_MEMBER_MONTH_IN_PMPM,
           COALESCE(COUNT_IF(K.COVERING_MEMBER_MONTH_ROWS = 0),0) AS LINES_WITHOUT_DATE_COVERING_PMPM,
           COALESCE(COUNT_IF(K.COVERING_MEMBER_MONTH_ROWS > 0),0) AS LINES_WITH_DATE_COVERING_PMPM,
           COALESCE(COUNT_IF(K.DATE_REFERENCE_ROWS > 1 OR K.MEMBER_REFERENCE_ROWS > 1),0) AS LINES_WITH_DUPLICATE_DATE_OR_MEMBER_REFERENCE
    FROM dental D
    JOIN classified_dates K
      ON (D.BENEFICIARY_ID = K.BENEFICIARY_ID
          OR (D.BENEFICIARY_ID IS NULL AND K.BENEFICIARY_ID IS NULL))
     AND (D.CLAIM_FIRST_SERVICE_DT = K.CLAIM_FIRST_SERVICE_DT
          OR (D.CLAIM_FIRST_SERVICE_DT IS NULL AND K.CLAIM_FIRST_SERVICE_DT IS NULL))
    GROUP BY D.CLAIM_STATUS_CD, K.PROFILE_MATCH, K.MATCH_REASON
)
SELECT R.*,
       SUM(R.CLAIM_LINE_COUNT) OVER (PARTITION BY R.CLAIM_STATUS_CD) AS STATUS_BASELINE_LINES,
       SUM(IFF(R.PROFILE_MATCH = 'No profile',R.CLAIM_LINE_COUNT,0))
           OVER (PARTITION BY R.CLAIM_STATUS_CD) AS STATUS_NO_PROFILE_LINES,
       SUM(IFF(R.PROFILE_MATCH = 'No profile',R.PAID_AMOUNT,0))
           OVER (PARTITION BY R.CLAIM_STATUS_CD) AS STATUS_NO_PROFILE_PAID_AMOUNT,
       B.CLAIM_MIN_SERVICE_DT, B.CLAIM_MAX_SERVICE_DT,
       P.PMPM_MIN_YR_MONTH, P.PMPM_MAX_YR_MONTH,
       P.PMPM_MIN_VALID_BEGIN_DT, P.PMPM_MAX_VALID_END_DT,
       P.PMPM_SOURCE_ROWS, P.PMPM_UNPARSEABLE_OR_NULL_MONTH_ROWS,
       CASE WHEN B.CLAIM_MIN_SERVICE_DT IS NULL OR P.PMPM_MIN_VALID_BEGIN_DT IS NULL
                  OR B.CLAIM_MAX_SERVICE_DT IS NULL OR P.PMPM_MAX_VALID_END_DT IS NULL THEN 'Unknown'
            WHEN GREATEST(B.CLAIM_MIN_SERVICE_DT,P.PMPM_MIN_VALID_BEGIN_DT)
                 <= LEAST(B.CLAIM_MAX_SERVICE_DT,P.PMPM_MAX_VALID_END_DT) THEN 'Yes'
            ELSE 'No' END AS GLOBAL_SPAN_RANGES_OVERLAP
FROM reason_totals R CROSS JOIN claim_bounds B CROSS JOIN pmpm_bounds P
ORDER BY R.CLAIM_STATUS_CD, R.MATCH_REASON;
